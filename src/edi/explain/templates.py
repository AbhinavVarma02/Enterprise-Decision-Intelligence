"""Deterministic explanation templates.

Every sentence is built from computed fields of the candidate and the validation report, so each
statement can be traced to a number or a gate result. No text is generated by a language model.
"""

from __future__ import annotations

from typing import Any

from edi.validation.schema import DecisionCandidate, ValidationReport

VERB = {
    "recommend": "Recommend",
    "investigate": "Investigate before acting",
    "defer": "Defer",
    "escalate": "Escalate for review",
    "reject": "Reject",
}


def _money(x: float | None, currency: str = "$") -> str:
    if x is None:
        return "n/a"
    sign = "-" if x < 0 else ""
    return f"{sign}{currency}{abs(x):,.0f}" if abs(x) >= 100 else f"{sign}{currency}{abs(x):,.2f}"


def describe_action(action: dict[str, float], unit: str = "units") -> str:
    parts = [f"{v:,.1f} {unit} via {k}" for k, v in action.items() if v > 1e-6]
    return ", ".join(parts) if parts else "no new order"


def explain(cand: DecisionCandidate, rep: ValidationReport, unit: str = "units") -> str:
    m: dict[str, Any] = rep.metrics
    lines = [f"{VERB[rep.outcome]}: {describe_action(cand.action, unit)}."]
    if m.get("expected_cost") is not None:
        alpha = int(round(cand.risk_tolerance.cvar_alpha * 100))
        lines.append(
            f"Modeled expected cost {_money(m['expected_cost'])}; average of the worst {100 - alpha}% of "
            f"scenarios {_money(m.get('cvar'))}."
        )
    fails = [g for g in rep.gates if g.status == "fail"]
    warns = [g for g in rep.gates if g.status == "warn"]
    for g in fails[:2]:
        lines.append(f"{g.name} failed: {g.summary.rstrip('.')}.")
    if rep.outcome == "investigate" and rep.value_of_information:
        v = rep.value_of_information
        lines.append(
            f"Checking {v.get('input', 'the input')} is worth about {_money(v['value_vs_candidate'])} in avoided cost, "
            f"more than its {_money(v['investigation_cost'])} cost."
        )
    if rep.recommended_action and rep.outcome in ("reject", "escalate"):
        lines.append(f"Suggested alternative: {describe_action(rep.recommended_action, unit)}.")
    if not fails and warns and rep.outcome == "recommend":
        lines.append(f"Noted: {warns[0].summary.rstrip('.')}.")
    return " ".join(lines)
